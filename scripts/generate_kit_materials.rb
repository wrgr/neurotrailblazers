  exc = %w[L23_pyr L4_exc L5_pyr L6_pyr]
  rate = lambda do |a, b|
    ea = exc.include?(a[:type])
    eb = exc.include?(b[:type])
    r = if ea && eb then a[:layer] == b[:layer] ? 0.10 : (a[:type] == 'L4_exc' && b[:type] == 'L23_pyr' ? 0.12 : 0.03)
        elsif ea then 0.22
        elsif eb then a[:type] == 'vip' ? 0.02 : 0.30
        else a[:type] == 'vip' ? 0.25 : 0.12
        end
    2.6 * r * Math.exp(-dist(a[:pos], b[:pos]) / 150.0)
  end
  edges = {}
  nodes.each do |a|
    nodes.each do |b|
      next if a.equal?(b)

      edges[[a[:id], b[:id]]] = geometric(rng, 0.55) if rng.rand < rate.call(a, b)
    end
