COLUMN_LAYERS = { 'L1' => [0, 100], 'L2/3' => [100, 350], 'L4' => [350, 500], 'L5' => [500, 750], 'L6' => [750, 950] }.freeze

def place(rng, layer)
  lo, hi = COLUMN_LAYERS.fetch(layer)
  [(rng.rand * 400).round(1), (lo + rng.rand * (hi - lo)).round(1), (rng.rand * 400).round(1)]
end

def geometric(rng, p)
  n = 1
  n += 1 while rng.rand > p
  n
end

