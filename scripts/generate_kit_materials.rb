def module13
  rng = Random.new(1313)
  dir = kit_dir(13)
  classes = { 'axon' => 0.38, 'spiny_dendrite' => 0.27, 'smooth_dendrite' => 0.19, 'glia_process' => 0.12,
              'merged_object' => 0.04 }
  # class means: path, caliber mean, caliber var, branches, tortuosity, pre syn, post syn, mito fraction
  means = {
    'axon' => [34, 0.35, 0.020, 2.5, 1.25, 3.0, 1.0, 0.07],
    'spiny_dendrite' => [30, 0.60, 0.050, 3.0, 1.18, 0.5, 5.0, 0.09],
    'smooth_dendrite' => [29, 0.55, 0.040, 3.0, 1.16, 0.5, 4.0, 0.11],
    'glia_process' => [25, 0.45, 0.080, 3.5, 1.35, 0.3, 0.5, 0.04],
    'merged_object' => [50, 0.55, 0.120, 5.0, 1.30, 2.0, 4.0, 0.08]
  }
  # Parents have a kind, and a kind only yields certain classes: a pyramidal
  # parent gives axon and spiny-dendrite fragments, an interneuron gives axon and
  # smooth-dendrite fragments, glia give glial processes. So fragments of one
  # parent share both a class mix and a per-parent feature signature, which is
  # what makes a random row split leak.
  kinds = { 'axon' => %w[pyr int], 'spiny_dendrite' => %w[pyr], 'smooth_dendrite' => %w[int],
            'glia_process' => %w[glia], 'merged_object' => %w[pyr int glia] }
  neurons = Array.new(600) do |i|
    kind = i < 330 ? 'pyr' : (i < 500 ? 'int' : 'glia')
    { id: 40_001 + i, kind: kind, block: [rng.rand(8), rng.rand(8)], batch: "B#{rng.rand(6) + 1}",
      offset: Array.new(8) { gaussian(rng, 0, 0.6) }, stain: gaussian(rng, 0, 4) }
  end
  by_kind = neurons.group_by { |n| n[:kind] }
  blocks = Hash.new { |h, k| h[k] = gaussian(rng, 0, 12) } # staining offset per 100 µm block
  rows = []
  4000.times do |i|
    cls = weighted_pick(rng, classes)
    n = by_kind.values_at(*kinds[cls]).flatten.sample(random: rng)
    m = means[cls]
    f = m.each_with_index.map { |mu, k| mu * Math.exp(n[:offset][k] + gaussian(rng, 0, 0.3)) }
    intensity = 120 + blocks[n[:block]] + n[:stain] + gaussian(rng, 0, 1.5)
    contains_error = cls == 'merged_object' || rng.rand < { 'axon' => 0.22, 'spiny_dendrite' => 0.15,
                                                             'smooth_dendrite' => 0.18, 'glia_process' => 0.35 }[cls]
    x = n[:block][0] * 100 + rng.rand * 100
