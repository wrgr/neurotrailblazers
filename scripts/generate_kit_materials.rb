def module03
  rng = Random.new(3003)
  dir = kit_dir(3)
  types = {
    'L23_pyr' => ['L2/3', 90], 'L4_exc' => ['L4', 70], 'L5_pyr' => ['L5', 60],
    'basket' => [nil, 40], 'martinotti' => [nil, 25], 'vip' => [nil, 15]
  }
  neurons = []
  nid = 100_001
  types.each do |type, (layer, n)|
    n.times do
      region = layer || %w[L2/3 L4 L5].sample(random: rng)
      depth = { 'L2/3' => [100, 300], 'L4' => [300, 450], 'L5' => [450, 700] }[region]
      neurons << { id: nid, type: type, region: region,
                   pos: [rng.rand * 300, depth[0] + rng.rand * (depth[1] - depth[0]), rng.rand * 300] }
      nid += 1
    end
  end
  exc = %w[L23_pyr L4_exc L5_pyr]
  out_weight = lambda do |pre, post|
    if exc.include?(pre.fetch(:type))
      exc.include?(post[:type]) ? 1.0 : 1.6
    else
      post[:type] == 'vip' ? 0.3 : 1.2
    end
  end
  rows = []
  sid = 1
  3000.times do
    pre = neurons.sample(random: rng)
    post = nil
    loop do
      cand = neurons.sample(random: rng)
      next if cand[:id] == pre[:id]

      d = dist(pre[:pos], cand[:pos])
      p = out_weight.call(pre, cand) * Math.exp(-d / 180.0) / 1.6
      if rng.rand < p
        post = cand
        break
      end
    end
    loc = vadd(post[:pos], [gaussian(rng, 0, 25), gaussian(rng, 0, 25), gaussian(rng, 0, 25)])
    size = (exc.include?(pre[:type]) ? 180 : 260) * Math.exp(gaussian(rng, 0, 0.6))
    rows << [sid, pre[:id], post[:id], pre[:type], post[:type], post[:region],
             loc[0].round(1), loc[1].round(1), loc[2].round(1), size.round]
    sid += 1
  end
  # Two percent of rows lack a postsynaptic cell type, as real annotation tables do;
  # schema validation in step 4 should find them.
  rows.each { |r| r[4] = '' if rng.rand < 0.02 }
  write_csv(File.join(dir, 'synapses_sample.csv'),
            %w[synapse_id pre_root_id post_root_id pre_cell_type post_cell_type region x_um y_um z_um size_vx],
            rows)
  meta = {
    'dataset' => 'synthetic-teaching-only',
    'version' => 'synthetic-synapses-v1',
    'generator' => GENERATOR,
    'seed' => 3003,
    'rows' => rows.size,
    'neurons' => neurons.size,
    'columns' => {
      'synapse_id' => 'row identifier',
      'pre_root_id' => 'synthetic presynaptic neuron ID (six digits; real CAVE root IDs are 18 digits)',
      'post_root_id' => 'synthetic postsynaptic neuron ID',
      'pre_cell_type' => 'L23_pyr, L4_exc, L5_pyr, basket, martinotti or vip',
      'post_cell_type' => 'same vocabulary; blank for about 2.5% of rows (missing annotation)',
      'region' => 'layer of the postsynaptic soma: L2/3, L4 or L5',
      'x_um y_um z_um' => 'synapse position in micrometers; y increases with depth from the pia',
      'size_vx' => 'cleft size in voxels (arbitrary synthetic units)'
    },
    'limitation' => 'Invented cell types, positions and connection rules; not a CAVE query and not a biological measurement.'
  }
  write(File.join(dir, 'synapses_sample.meta.json'), JSON.pretty_generate(meta))
  write(File.join(dir, 'README.md'), <<~MD)
    # Module 03 kit: offline synapse table

    #{SYNTHETIC_BANNER}

    Use this when CAVE access is unavailable (Module 03 studio activity, step 3). It
    has the shape of a small synapse query result, so every step of the activity
    works on it: schema validation, filtering by region, grouping by cell-type pair,
    a figure, and a CSV plus metadata export.

    | File | What it is |
    |---|---|
    | `synapses_sample.csv` | #{delim(rows.size)} synapses among #{neurons.size} invented neurons |
    | `synapses_sample.meta.json` | Column definitions, version string and seed |

    Record `synthetic-synapses-v1` as the dataset version in your notebook header, in
    the place a materialization version would go. The file deliberately contains a
    few rows with a blank `post_cell_type`; your schema check should report how many.

    Load it with pandas:

    ```python
    import pandas as pd
    syn = pd.read_csv("synapses_sample.csv")
    print(syn.dtypes, len(syn))
    print(syn["post_cell_type"].eq("").sum() + syn["post_cell_type"].isna().sum(), "rows lack a post type")
    ```

    **What this file cannot teach.** Authentication, materialization versions that
    change under you, and query limits. Do those against a real CAVE endpoint when you
    have access; the [Dataset Access](/datasets/access/) page lists the entry points.
  MD
end

