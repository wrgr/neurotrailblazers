# Generate the synthetic teaching kits under assets/kits/.
#
# Why this exists. The session kits for Modules 03-07 and 09-11 (and several later
# modules) told learners to open "the provided" sample CSV, patch set, notebook or
# metric script, and the site published none of them (NEXT_CONTENT_PASS.md item 5;
# audit in docs/reviews/2026-09-kit-materials-audit.md). Where an honest stand-in
# could be built without pretending to be real data, it is built here. Where it could
# not (real EM image patches), the module was rewritten to use public viewers instead.
#
# Every file this script writes is SYNTHETIC. Nothing is sampled from MICrONS, H01,
# FlyWire or any other dataset; distributions are chosen by hand to make one teaching
# point each, and every README says so in its first lines. Output is deterministic:
# each kit draws from its own fixed seed, and floats are written with fixed precision,
# so re-running the script on any Ruby >= 3.1 reproduces the committed bytes.
#
# The hand-written analysis scripts in the kits (qc_metrics.py, morphometry.py,
# profile_join.py) are not generated. This script only lists them in the manifest.
#
# Run from anywhere:  ruby scripts/generate_kit_materials.rb
# Then check:         ruby scripts/validate_kit_materials.rb

