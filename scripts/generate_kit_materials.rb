def manifest
  files = Dir.glob(File.join(KITS, '**', '*')).select { |f| File.file?(f) }.sort
  files.reject! { |f| File.basename(f) == 'manifest.json' }
  hand = %w[qc_metrics.py morphometry.py profile_join.py]
  entries = files.map do |f|
    rel = f.sub("#{ROOT}/", '')
    {
      'path' => rel,
      'sha256' => Digest::SHA256.file(f).hexdigest,
      'bytes' => File.size(f),
      'source' => hand.include?(File.basename(f)) ? 'hand-written' : GENERATOR
    }
  end
  write(File.join(KITS, 'manifest.json'), JSON.pretty_generate(
    'description' => 'Every file under assets/kits/, with its checksum. Regenerate with ' \
                     "ruby #{GENERATOR}; scripts/validate_kit_materials.rb checks this list.",
    'files' => entries
  ))
  entries.size
end

