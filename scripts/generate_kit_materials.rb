# ------------------------------------------------------------------ helpers

def kit_dir(num)
  dir = File.join(KITS, format('module%02d', num))
  FileUtils.mkdir_p(dir)
  dir
end

def write(path, text)
  FileUtils.mkdir_p(File.dirname(path))
  File.write(path, text.end_with?("\n") ? text : "#{text}\n")
end

def write_csv(path, header, rows)
  lines = [header.join(',')]
  rows.each do |row|
    lines << row.map { |v| csv_cell(v) }.join(',')
  end
  write(path, lines.join("\n"))
end

def csv_cell(value)
  s = case value
      when Float then value.to_s
      when nil then ''
      else value.to_s
      end
  s.match?(/[",\n]/) ? "\"#{s.gsub('"', '""')}\"" : s
end

def poisson(rng, lambda)
  return 0 if lambda <= 0

  l = Math.exp(-lambda)
  k = 0
  p = 1.0
  loop do
    p *= rng.rand
    break if p <= l

    k += 1
  end
  k
end

def gaussian(rng, mean = 0.0, sd = 1.0)
  u1 = rng.rand
  u1 = 1e-12 if u1 < 1e-12
  u2 = rng.rand
  mean + sd * Math.sqrt(-2.0 * Math.log(u1)) * Math.cos(2 * Math::PI * u2)
end

def weighted_pick(rng, weights)
  total = weights.values.sum
  r = rng.rand * total
  weights.each do |key, w|
    return key if r < w

    r -= w
  end
  weights.keys.last
end

def delim(n) = n.to_s.reverse.scan(/\d{1,3}/).join(',').reverse

def dist(a, b)
  Math.sqrt(a.zip(b).sum { |p, q| (p - q)**2 })
end

# ------------------------------------------------------------------ vectors

def vadd(a, b) = a.zip(b).map { |p, q| p + q }
def vscale(a, s) = a.map { |p| p * s }

def vnorm(a)
  n = Math.sqrt(a.sum { |p| p * p })
  n.zero? ? [0.0, 1.0, 0.0] : a.map { |p| p / n }
end

def jitter(rng, dir, amount)
  vnorm(vadd(dir, [gaussian(rng, 0, amount), gaussian(rng, 0, amount), gaussian(rng, 0, amount)]))
end

# ------------------------------------------------------------------ SWC trees
#
# A deliberately simple grower: a dendrite is a run of 2 µm steps with a small
# random wobble, bifurcating at its end until a depth limit. Spines are Poisson
# draws per step at a density that can depend on path distance from the soma.
# The grower stops a branch where it crosses the volume boundary and records the
# node, which is how truncation is represented.

class SwcTree
  attr_reader :nodes, :spines, :face_nodes

  def initialize(bounds)
    @bounds = bounds # [[xmin,xmax],[ymin,ymax],[zmin,zmax]] or nil
    @nodes = []
    @spines = Hash.new(0)
    @face_nodes = []
  end

  def add(type, pos, radius, parent)
    id = @nodes.size + 1
    @nodes << [id, type, pos, radius, parent]
    id
  end

  def outside?(pos)
    return false unless @bounds

    pos.each_with_index.any? { |c, i| c < @bounds[i][0] || c > @bounds[i][1] }
  end

  # Moves a point that left the volume back onto the face it crossed.
  def clamp(pos)
    pos.each_with_index.map { |c, i| c.clamp(@bounds[i][0], @bounds[i][1]) }
  end

  def pos(id) = @nodes[id - 1][2]

  # grow a branch; opts: length, radius, depth, max_depth, wobble, spine (lambda path_um -> density),
  # split_angle, shrink
  def grow(rng, parent, start, dir, type, opts, path0 = 0.0)
    step = 2.0
    steps = [(opts[:length] / step).round, 1].max
    cur = parent
    p = start
    r = opts[:radius]
    path = path0
    steps.times do
      dir = jitter(rng, dir, opts[:wobble])
      np = vadd(p, vscale(dir, step))
      path += step
      if outside?(np)
        np = clamp(np)
        id = add(type, np, r, cur)
        @face_nodes << id
        @spines[id] += poisson(rng, opts[:spine].call(path, type) * step)
        return
      end
      id = add(type, np, r, cur)
      @spines[id] += poisson(rng, opts[:spine].call(path, type) * step)
      cur = id
      p = np
      r = [r * opts.fetch(:taper, 0.985), 0.25].max
    end
    return if opts[:depth] >= opts[:max_depth]

    2.times do
      child_dir = jitter(rng, dir, opts[:split_angle])
      child = opts.merge(length: opts[:length] * (0.6 + 0.3 * rng.rand),
                         radius: r * 0.8, depth: opts[:depth] + 1)
      grow(rng, cur, p, child_dir, type, child, path)
    end
  end

  def swc_text(header_lines)
    lines = header_lines.map { |l| "# #{l}" }
    lines << '# columns: id type x y z radius parent  (type 1 soma, 3 basal dendrite, 4 apical dendrite)'
    @nodes.each do |id, type, pos, r, parent|
      lines << format('%d %d %.2f %.2f %.2f %.2f %d', id, type, pos[0], pos[1], pos[2], r, parent)
    end
    lines.join("\n")
  end
end

PYR_SPINES = lambda do |path, type|
  if type == 4 && path < 40 then 0.15 # proximal apical trunk carries few spines
  elsif path < 12 then 0.3            # first microns of any dendrite are nearly smooth
  else 1.3
  end
end
SMOOTH_SPINES = ->(_path, _type) { 0.03 }

def pyramidal(rng, tree, soma, apical_dir: [0.0, 1.0, 0.0], basal_dirs: nil, apical_len: 110,
              basal_len: 42, spine: PYR_SPINES)
  sid = tree.add(1, soma, 7.0, -1)
  base = { radius: 1.1, depth: 0, max_depth: 2, wobble: 0.12, split_angle: 0.55, spine: spine }
  tree.grow(rng, sid, soma, vnorm(apical_dir), 4,
            base.merge(length: apical_len, radius: 1.8, max_depth: 2, taper: 0.992))
  basal_dirs ||= Array.new(5) do |i|
    a = 2 * Math::PI * i / 5 + rng.rand * 0.4
    [Math.cos(a), -0.35 - 0.2 * rng.rand, Math.sin(a)]
  end
  basal_dirs.each { |d| tree.grow(rng, sid, soma, vnorm(d), 3, base.merge(length: basal_len)) }
  sid
end

def interneuron(rng, tree, soma, n_dend: 6, length: 55, spine: SMOOTH_SPINES, max_depth: 3)
  sid = tree.add(1, soma, 6.0, -1)
  n_dend.times do |i|
    a = 2 * Math::PI * i / n_dend + rng.rand * 0.5
    d = [Math.cos(a), gaussian(rng, 0, 0.6), Math.sin(a)]
    tree.grow(rng, sid, soma, vnorm(d), 3,
              { length: length, radius: 0.8, depth: 0, max_depth: max_depth, wobble: 0.22,
                split_angle: 0.7, spine: spine })
  end
  sid
end

