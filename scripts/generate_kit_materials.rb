  pop = { 'L23_pyr' => ['L2/3', 90], 'L4_exc' => ['L4', 60], 'basket' => [nil, 25], 'martinotti' => [nil, 15],
          'vip' => [nil, 10] }
  nodes = []
  pop.each do |type, (layer, n)|
    n.times do
      l = layer || %w[L2/3 L4].sample(random: rng)
      nodes << { type: type, layer: l, pos: place(rng, l) }
    end
  end
  nodes.shuffle!(random: rng)
  nodes.each_with_index { |n, i| n[:id] = 30_001 + i }
  exc = %w[L23_pyr L4_exc]
  rate = lambda do |a, b|
    ea = exc.include?(a[:type])
    eb = exc.include?(b[:type])
    r = if ea && eb then a[:layer] == b[:layer] ? 0.05 : (a[:type] == 'L4_exc' ? 0.06 : 0.015)
        elsif ea then 0.14
        elsif eb then { 'basket' => 0.24, 'martinotti' => 0.16, 'vip' => 0.01 }[a[:type]]
        else a[:type] == 'vip' ? 0.20 : 0.06
        end
    2.7 * r * Math.exp(-dist(a[:pos], b[:pos]) / 120.0)
  end
  compartments = lambda do |pre, post|
    if exc.include?(pre[:type])
      exc.include?(post[:type]) ? { 'spine' => 0.8, 'distal_dendrite' => 0.15, 'proximal_dendrite' => 0.05 } :
                                  { 'proximal_dendrite' => 0.5, 'distal_dendrite' => 0.35, 'soma' => 0.15 }
    else
      case pre[:type]
      when 'basket' then { 'soma' => 0.55, 'proximal_dendrite' => 0.3, 'distal_dendrite' => 0.1, 'uncertain' => 0.05 }
      when 'martinotti' then { 'distal_dendrite' => 0.8, 'spine' => 0.1, 'uncertain' => 0.1 }
      else { 'distal_dendrite' => 0.5, 'proximal_dendrite' => 0.4, 'uncertain' => 0.1 }
      end
    end
  end
  synapses = []
  sid = 1
  nodes.each do |a|
    nodes.each do |b|
      next if a.equal?(b)
      next unless rng.rand < rate.call(a, b)

      geometric(rng, 0.5).times do
        comp = weighted_pick(rng, compartments.call(a, b))
        gray = if comp == 'uncertain' then 'uncertain'
               elsif exc.include?(a[:type]) then rng.rand < 0.95 ? 'asymmetric' : 'uncertain'
               else rng.rand < 0.9 ? 'symmetric' : 'uncertain'
               end
        loc = vadd(b[:pos], [gaussian(rng, 0, 30), gaussian(rng, 0, 30), gaussian(rng, 0, 30)])
        synapses << [sid, a[:id], b[:id], comp, gray, loc[0].round(1), loc[1].round(1), loc[2].round(1)]
        sid += 1
      end
    end
  end
  write_csv(File.join(dir, 'nodes.csv'), %w[node_id cell_type layer soma_x_um soma_y_um soma_z_um],
            nodes.sort_by { |n| n[:id] }.map { |n| [n[:id], n[:type], n[:layer], *n[:pos]] })
  write_csv(File.join(dir, 'synapses.csv'),
            %w[synapse_id pre_id post_id compartment gray_type x_um y_um z_um], synapses)
  edge_count = synapses.map { |s| [s[1], s[2]] }.uniq.size

  # Warm-up subgraph: 15 neurons whose mutual synapses total exactly 50. Search
  # spatially compact candidate sets until one fits; seeded, so it is reproducible.
  by_id = nodes.to_h { |n| [n[:id], n] }
  small = nil
  srng = Random.new(1112)
  2000.times do
    center = nodes.sample(random: srng)
    pool = nodes.sort_by { |n| dist(n[:pos], center[:pos]) }.first(30)
    set = pool.sample(15, random: srng).map { |n| n[:id] }
    inside = synapses.select { |s| set.include?(s[1]) && set.include?(s[2]) }
    next unless inside.size == 50
    next unless set.map { |i| by_id[i][:type] }.uniq.size >= 3

    small = [set, inside]
    break
  end
  raise 'no 15-neuron, 50-synapse subgraph found; change the search seed' unless small

  set, inside = small
  write_csv(File.join(dir, 'small_nodes.csv'), %w[node_id cell_type layer],
            set.sort.map { |i| [i, by_id[i][:type], by_id[i][:layer]] })
  write_csv(File.join(dir, 'small_synapses.csv'), %w[synapse_id pre_id post_id compartment gray_type],
            inside.map { |s| s.first(5) })
  write(File.join(dir, 'README.md'), <<~MD)
    # Module 11 kit: a 200-neuron L2/3-L4 subgraph with synapse-level detail

    #{SYNTHETIC_BANNER}

    The Module 11 motif activity needs two things the graph abstraction throws away:
    where each synapse lands, and its Gray type. This kit keeps both.

    | File | Used in | What it is |
    |---|---|---|
    | `small_nodes.csv`, `small_synapses.csv` | Run-of-show 24:00-38:00 | 15 neurons and the 50 synapses among them, for counting 3-node motifs by hand |
    | `nodes.csv` | Studio | #{nodes.size} neurons: cell type, layer (L2/3 or L4), soma position |
    | `synapses.csv` | Studio | #{delim(synapses.size)} synapses (#{delim(edge_count)} directed connections): pre, post, postsynaptic compartment, Gray type, position |

    Collapse `synapses.csv` to edges by counting rows per (`pre_id`, `post_id`); keep
    the count so you can re-run at a threshold of two synapses. DotMotif or NetworkX
    both work on the resulting edge list.

    **How it was built.** Connection probability depends on the two cell types and
    falls off with soma distance (length constant 120 µm). Basket-type cells place
    most synapses on the soma or proximal dendrite; Martinotti-type cells place most on
    distal dendrites. So a count of E to I to E loops will be enriched against a
    degree-preserving null largely because of cell-type composition and proximity,
    and splitting the loops by compartment will separate two different circuits. The
    alternative explanations the studio asks for are built in; the kit contains no
    "wiring rule" beyond type, distance and compartment preferences.
  MD
end

