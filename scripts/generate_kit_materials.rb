      m[6] = 1.5  # and faint postsynaptic densities go undetected
    end
    f = m.map { |mu| mu * Math.exp(gaussian(rng, 0, 0.55)) }
    contains_error = cls == 'merged_object' || rng.rand < 0.2
    held << [format('H%04d', i + 1), 90_001 + rng.rand(150), 'domain2', 'D2', '', '',
             f[0].round(1), f[1].round(3), f[2].round(4), f[3].round, f[4].round(3), f[5].round, f[6].round,
             f[7].round(3), (95 + gaussian(rng, 0, 8)).round(1), cls, contains_error ? 1 : 0]
  end
  write_csv(File.join(dir, 'heldout_domain.csv'), header, held)
  write(File.join(dir, 'README.md'), <<~MD)
    # Module 13 kit: labeled neurite fragments

    #{SYNTHETIC_BANNER}

    The fragment set for Module 13: 4,000 labeled fragments from 600
    neurons in five classes, plus 1,000 fragments from a second, differently stained
    domain for the transfer test.

    | File | What it is |
    |---|---|
    | `fragments.csv` | Training domain. Prevalences near 38 / 27 / 19 / 12 / 4 % |
    | `heldout_domain.csv` | Second domain, same columns. Use it once, at the end. |

    | Column | Meaning |
    |---|---|
    | `parent_neuron_id` | Group for a grouped split |
    | `block_100um`, `x_um`, `y_um` | 100 µm spatial tile and position, for a spatial-block split |
    | `proofread_batch` | Annotation batch, for a batch split |
    | `path_length_um` ... `mito_volume_fraction` | The morphological features from the module's Concept 1 |
    | `mean_intensity` | Raw image intensity. Read the module on what this encodes before you use it |
    | `label` | axon, spiny_dendrite, smooth_dendrite, glia_process, merged_object |
    | `contains_error` | 1 if a reviewer would find an error in this segment; the target for precision at *k* = 500 |

    **What is built in.** Fragments of one neuron share a per-neuron offset on every
    feature, so a random row split leaks. Fragments in one 100 µm block share an
    intensity offset. In the held-out domain, mitochondria are under-segmented and
