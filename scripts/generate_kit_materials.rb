    | `qc_metrics.py` | Everyone | Computes before/after quality indicators for a list of fixed IDs. Python 3, no packages. |

    **Fixing on paper.** No public volume lets a class edit a segmentation, so a "fix"
    here means: you commit to correcting a flagged item, write its log line, and then
    let the script apply what that correction would have changed. The script stands
    in for re-measuring against a proofread reference region. It knows the answer;
    you do not, which is the situation a real triage is in.

    ```bash
    python3 qc_metrics.py                      # baseline, nothing fixed
    python3 qc_metrics.py --fixed #{fixes}     # after your fixes (IDs comma-separated)
    ```

    #{warmup}

